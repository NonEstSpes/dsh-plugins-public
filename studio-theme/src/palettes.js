/** Full registered definitions also replace the product icon sprite while selected. */
export function studioDefinitions(icons) {
  return ['light', 'dark'].map((scheme, index) => ({
    id: `studio-${scheme}`,
    colorScheme: scheme,
    tokens: {
      ...Object.fromEntries(Object.entries(colors).map(([name, values]) => [name, values[index]])),
      ...geometry,
    },
    icons,
  }));
}
